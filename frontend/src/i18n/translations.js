export const normalizeTranslationKey = (value = "") =>
  String(value).replace(/\s+/g, " ").trim().toLowerCase();

export const translateLabel = (text, language = DEFAULT_LANGUAGE) => {
  if (!text || language === DEFAULT_LANGUAGE) return text;
  const key = normalizeTranslationKey(text);
  const dictionary = sharedTranslations[key];
  return dictionary?.[language] || text;
};

export const formatWithTemplate = (template, replacements = {}) =>
  Object.entries(replacements).reduce(
    (acc, [key, value]) => acc.replaceAll(`{${key}}`, value),
    template
  );
